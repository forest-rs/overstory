/// Factory that builds a templated control's visual subtree.
///
/// Implementations create generated nodes through [`TemplateContext`]. Nodes
/// inserted that way are explicitly tagged with `templated_parent =
/// Some(owner)` and optional owner-local [`understory_style::PartTag`]s.
/// Overstory uses those tags to route owner-state selectors through template
/// descendants, find named parts after expansion, and clean binding graph edges
/// when parts are removed.
///
/// Templates are immutable recipes. They may be static unit structs, reusable
/// data-driven specs, or owned values stored behind a [`ControlTemplate`].
pub trait Template: Send + Sync {
    /// Builds this template's subtree under `owner`.
    fn instantiate(&self, cx: &mut TemplateContext<'_>);
}
