use understory_style::{ClassId, PartTag};

/// Factory that builds a templated control's visual subtree.
///
/// Implementations create generated nodes through [`TemplateContext`]. Nodes
/// inserted that way are explicitly tagged with `templated_parent =
/// Some(owner)` and optional owner-local [`PartTag`]s. Overstory uses those
/// tags to route owner-state selectors through template descendants, find
/// named parts after expansion, and clean binding graph edges when parts are
/// removed.
///
/// Templates are stored as `&'static dyn Template`, so they should be unit
/// structs or `LazyLock<...>`-style statics rather than per-instance values.
/// Controls can expose builder-level template overrides when their behavior
/// does not depend on the default visual subtree.
pub trait Template: Sync {
    /// Builds this template's subtree under `owner`.
    fn instantiate(&self, cx: &mut TemplateContext<'_>);
}

/// Stable per-template item key for repeated template parts.
///
/// Single parts normally use `None`. Repeated parts, such as generated slider
/// ticks, can use a key to preserve owner-local identity without inventing a
/// distinct global widget type for each repeated node.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub struct TemplateItemKey(u64);

impl TemplateItemKey {
    /// Creates a key from a caller-defined integer.
    #[must_use]
    #[inline]
    pub const fn new(value: u64) -> Self {
        Self(value)
    }

    /// Returns the raw integer value.
    #[must_use]
    #[inline]
    pub const fn value(self) -> u64 {
        self.0
    }
}

/// Semantic slot contract between a widget and its template.
///
/// Slots identify what role a generated element plays for the owning control
/// without requiring the template to use a specific visual part name. A slot
/// can also carry an owner-local [`PartTag`] when the generated element should
/// participate in part styling.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub struct TemplateSlot {
    name: &'static str,
    part_tag: Option<PartTag>,
}

impl TemplateSlot {
    /// Creates a slot from a stable static name.
    #[must_use]
    #[inline]
    pub const fn new(name: &'static str) -> Self {
        Self {
            name,
            part_tag: None,
        }
    }

    /// Returns the stable slot name.
    #[must_use]
    #[inline]
    pub const fn name(self) -> &'static str {
        self.name
    }

    /// Returns the owner-local styling part tag for this slot, if any.
    #[must_use]
    #[inline]
    pub const fn part_tag(self) -> Option<PartTag> {
        self.part_tag
    }

    /// Returns this slot with an owner-local style part tag.
    #[must_use]
    #[inline]
    pub const fn with_part_tag(mut self, part_tag: PartTag) -> Self {
        self.part_tag = Some(part_tag);
        self
    }
}

/// One element generated by a template and registered as a slot and/or part.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct TemplatePart {
    slot: Option<TemplateSlot>,
    part_tag: Option<PartTag>,
    key: Option<TemplateItemKey>,
    element: ElementId,
}

impl TemplatePart {
    /// Returns the semantic slot this part fills, if any.
    #[must_use]
    #[inline]
    pub fn slot(&self) -> Option<TemplateSlot> {
        self.slot
    }

    /// Returns the owner-local styling part tag, if any.
    #[must_use]
    #[inline]
    pub fn part_tag(&self) -> Option<PartTag> {
        self.part_tag
    }

    /// Returns the optional repeated-item key.
    #[must_use]
    #[inline]
    pub fn key(&self) -> Option<TemplateItemKey> {
        self.key
    }

    /// Returns the generated element.
    #[must_use]
    #[inline]
    pub fn element(&self) -> ElementId {
        self.element
    }
}

/// Description of one child element a template wants to insert.
pub struct TemplateChild {
    widget: Box<dyn Widget>,
    slot: Option<TemplateSlot>,
    part_tag: Option<PartTag>,
    key: Option<TemplateItemKey>,
}

impl core::fmt::Debug for TemplateChild {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("TemplateChild")
            .field("slot", &self.slot)
            .field("part_tag", &self.part_tag)
            .field("key", &self.key)
            .finish_non_exhaustive()
    }
}

impl TemplateChild {
    /// Creates an unnamed child with no retained slot or part record.
    #[must_use]
    #[inline]
    pub fn widget(widget: Box<dyn Widget>) -> Self {
        Self {
            widget,
            slot: None,
            part_tag: None,
            key: None,
        }
    }

    /// Creates a child that fills a semantic template slot.
    #[must_use]
    #[inline]
    pub fn slot(slot: TemplateSlot, widget: Box<dyn Widget>) -> Self {
        Self::widget(widget).with_slot(slot)
    }

    /// Creates a child with an owner-local part tag.
    #[must_use]
    #[inline]
    pub fn part(part_tag: PartTag, widget: Box<dyn Widget>) -> Self {
        Self::widget(widget).with_part(part_tag)
    }

    /// Assigns this child to a semantic template slot.
    #[must_use]
    #[inline]
    pub fn with_slot(mut self, slot: TemplateSlot) -> Self {
        self.slot = Some(slot);
        self
    }

    /// Assigns an owner-local part tag to this child.
    #[must_use]
    #[inline]
    pub fn with_part(mut self, part_tag: PartTag) -> Self {
        self.part_tag = Some(part_tag);
        self
    }

    /// Assigns a stable repeated-item key to this child.
    #[must_use]
    #[inline]
    pub fn with_key(mut self, key: TemplateItemKey) -> Self {
        self.key = Some(key);
        self
    }
}

/// Retained result of expanding one element's default template.
///
/// The instance records the generated part elements and binding ids created
/// while the template expanded. It is intentionally owner-local: callers ask
/// for `owner + PartTag`, not for global widget-type identities on parts.
#[derive(Debug)]
pub struct TemplateInstance {
    owner: ElementId,
    parts: Vec<TemplatePart>,
    bindings: Vec<BindingId>,
}

impl TemplateInstance {
    pub(crate) fn new(owner: ElementId) -> Self {
        Self {
            owner,
            parts: Vec::new(),
            bindings: Vec::new(),
        }
    }

    /// Returns the element whose template produced this instance.
    #[must_use]
    #[inline]
    pub fn owner(&self) -> ElementId {
        self.owner
    }

    /// Returns all registered parts in template creation order.
    #[must_use]
    #[inline]
    pub fn part_records(&self) -> &[TemplatePart] {
        &self.parts
    }

    /// Returns the first element registered for `tag`, if any.
    ///
    /// Use [`Self::parts`] when the part tag is repeated.
    #[must_use]
    pub fn part(&self, tag: PartTag) -> Option<ElementId> {
        self.parts
            .iter()
            .find(|part| part.part_tag == Some(tag))
            .map(|part| part.element)
    }

    /// Returns the element registered for `tag` and `key`, if any.
    #[must_use]
    pub fn keyed_part(&self, tag: PartTag, key: TemplateItemKey) -> Option<ElementId> {
        self.parts
            .iter()
            .find(|part| part.part_tag == Some(tag) && part.key == Some(key))
            .map(|part| part.element)
    }

    /// Returns the first element registered for `slot`, if any.
    ///
    /// Use [`Self::slots`] when the slot is repeated.
    #[must_use]
    pub fn slot(&self, slot: TemplateSlot) -> Option<ElementId> {
        self.parts
            .iter()
            .find(|part| part.slot == Some(slot))
            .map(|part| part.element)
    }

    /// Returns the element registered for `slot` and `key`, if any.
    #[must_use]
    pub fn keyed_slot(&self, slot: TemplateSlot, key: TemplateItemKey) -> Option<ElementId> {
        self.parts
            .iter()
            .find(|part| part.slot == Some(slot) && part.key == Some(key))
            .map(|part| part.element)
    }

    /// Returns all elements registered for `tag`, in template creation order.
    pub fn parts(&self, tag: PartTag) -> impl Iterator<Item = ElementId> + '_ {
        self.parts
            .iter()
            .filter(move |part| part.part_tag == Some(tag))
            .map(|part| part.element)
    }

    /// Returns all elements registered for `slot`, in template creation order.
    pub fn slots(&self, slot: TemplateSlot) -> impl Iterator<Item = ElementId> + '_ {
        self.parts
            .iter()
            .filter(move |part| part.slot == Some(slot))
            .map(|part| part.element)
    }

    /// Returns binding ids created while expanding the template.
    #[must_use]
    #[inline]
    pub fn binding_ids(&self) -> &[BindingId] {
        &self.bindings
    }

    pub(crate) fn remove_element(&mut self, element: ElementId) {
        self.parts.retain(|part| part.element != element);
    }

    fn push_part(
        &mut self,
        slot: Option<TemplateSlot>,
        part_tag: Option<PartTag>,
        key: Option<TemplateItemKey>,
        element: ElementId,
    ) {
        self.parts.push(TemplatePart {
            slot,
            part_tag,
            key,
            element,
        });
    }

    fn push_binding(&mut self, id: BindingId) {
        self.bindings.push(id);
    }
}

/// Expansion context passed to a [`Template`].
///
/// The context is the canonical way for templates to create generated parts,
/// bind owner properties into those parts, and install template-owned
/// behavior. It keeps template bookkeeping local to expansion instead of
/// relying on ambient `Ui` insertion state.
#[derive(Debug)]
pub struct TemplateContext<'a> {
    ui: &'a mut Ui,
    owner: ElementId,
    instance: TemplateInstance,
}

impl<'a> TemplateContext<'a> {
    pub(crate) fn new(ui: &'a mut Ui, owner: ElementId) -> Self {
        Self {
            ui,
            owner,
            instance: TemplateInstance::new(owner),
        }
    }

    pub(crate) fn finish(self) -> TemplateInstance {
        self.instance
    }

    /// Returns the element whose template is currently expanding.
    #[must_use]
    #[inline]
    pub fn owner(&self) -> ElementId {
        self.owner
    }

    /// Returns Overstory's built-in property handles.
    #[must_use]
    #[inline]
    pub fn properties(&self) -> &BuiltInProperties {
        self.ui.properties()
    }

    /// Inserts a generated child directly under the template owner.
    pub fn insert(&mut self, child: TemplateChild) -> ElementId {
        self.insert_under(self.owner, child)
    }

    /// Inserts a generated child under an existing template-generated parent.
    pub fn insert_under(&mut self, parent: ElementId, child: TemplateChild) -> ElementId {
        let part_tag = child
            .part_tag
            .or_else(|| child.slot.and_then(TemplateSlot::part_tag));
        let id = self
            .ui
            .insert_template_child(self.owner, parent, part_tag, Some(child.widget));
        if child.slot.is_some() || part_tag.is_some() {
            self.instance.push_part(child.slot, part_tag, child.key, id);
        }
        id
    }

    /// Adds a class to a generated element.
    pub fn add_class(&mut self, id: ElementId, class: ClassId) {
        self.ui.add_class(id, class);
    }

    /// Writes a local property value through the owning [`Ui`].
    pub fn set_local<T: Clone + PartialEq + 'static>(
        &mut self,
        id: ElementId,
        property: Property<T>,
        value: T,
    ) {
        self.ui.set_local(id, property, value);
    }

    /// Reads a local property value or returns `default`.
    ///
    /// This is intentionally local-only; template setup should not
    /// accidentally couple itself to cascade resolution.
    #[must_use]
    pub fn read_local_or<T: Clone + 'static>(
        &self,
        id: ElementId,
        property: Property<T>,
        default: T,
    ) -> T {
        self.ui
            .get(id)
            .and_then(|el| el.get_local_value(property).cloned())
            .unwrap_or(default)
    }

    /// Registers a one-way binding and records it on the retained instance.
    pub fn bind<T>(
        &mut self,
        source: PropertyEndpoint<ElementId, T>,
        target: PropertyEndpoint<ElementId, T>,
    ) -> Result<BindingId, BindingError<ElementId>>
    where
        T: Clone + 'static,
    {
        let id = self.ui.bind(source, target)?;
        self.instance.push_binding(id);
        Ok(id)
    }

    /// Binds an owner property into a generated part property.
    pub fn bind_owner_to_part<T>(
        &mut self,
        owner_property: Property<T>,
        part: ElementId,
        part_property: Property<T>,
    ) -> Result<BindingId, BindingError<ElementId>>
    where
        T: Clone + 'static,
    {
        self.bind(
            PropertyEndpoint::new(self.owner, owner_property),
            PropertyEndpoint::new(part, part_property),
        )
    }

    /// Registers a click handler on `id`.
    pub fn on_click<F>(&mut self, id: ElementId, handler: F)
    where
        F: FnMut(&mut Ui, ClickEvent<'_>) + 'static,
    {
        self.ui.on_control_click(id, handler);
    }

    /// Registers a drag handler on `id`.
    pub fn on_drag<F>(&mut self, id: ElementId, handler: F)
    where
        F: FnMut(&mut Ui, DragEvent<'_>) + 'static,
    {
        self.ui.on_control_drag(id, handler);
    }

    /// Registers a key handler on `id`.
    pub fn on_key<F>(&mut self, id: ElementId, handler: F)
    where
        F: FnMut(&mut Ui, KeyEvent<'_>) + 'static,
    {
        self.ui.on_control_key(id, handler);
    }
}

/// A data-driven default template.
///
/// `TemplateSpec` is intentionally only a compact description of normal
/// element-tree construction. It does not own layout, styling, or presentation;
/// those remain ordinary properties and cascade output on the generated
/// elements.
#[derive(Copy, Clone, Debug)]
pub struct TemplateSpec {
    nodes: &'static [TemplateNode],
}

impl TemplateSpec {
    /// Creates a spec from top-level template nodes.
    #[must_use]
    #[inline]
    pub const fn new(nodes: &'static [TemplateNode]) -> Self {
        Self { nodes }
    }

    /// Returns the top-level nodes in this spec.
    #[must_use]
    #[inline]
    pub const fn nodes(&self) -> &'static [TemplateNode] {
        self.nodes
    }
}

impl Template for TemplateSpec {
    fn instantiate(&self, cx: &mut TemplateContext<'_>) {
        for node in self.nodes {
            instantiate_spec_node(cx, cx.owner(), node);
        }
    }
}

/// Factory for a widget node in a [`TemplateSpec`].
#[derive(Copy, Clone)]
pub struct TemplateWidgetFactory {
    create: fn() -> Box<dyn Widget>,
}

impl core::fmt::Debug for TemplateWidgetFactory {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("TemplateWidgetFactory")
            .finish_non_exhaustive()
    }
}

impl TemplateWidgetFactory {
    /// Creates a factory from a zero-argument widget constructor.
    #[must_use]
    #[inline]
    pub const fn new(create: fn() -> Box<dyn Widget>) -> Self {
        Self { create }
    }

    /// Creates a surface-only template part widget.
    #[must_use]
    #[inline]
    pub const fn surface() -> Self {
        Self::new(surface_template_widget)
    }

    fn create(self) -> Box<dyn Widget> {
        (self.create)()
    }
}

fn surface_template_widget() -> Box<dyn Widget> {
    Box::new(SurfacePartWidget)
}

/// One node in a [`TemplateSpec`].
#[derive(Copy, Clone, Debug)]
pub struct TemplateNode {
    widget: TemplateWidgetFactory,
    slot: Option<TemplateSlot>,
    part: Option<PartTag>,
    key: Option<TemplateItemKey>,
    classes: &'static [ClassId],
    bindings: &'static [TemplateBinding],
    children: &'static [Self],
}

impl TemplateNode {
    /// Creates a node with the supplied widget factory.
    #[must_use]
    #[inline]
    pub const fn widget(widget: TemplateWidgetFactory) -> Self {
        Self {
            widget,
            slot: None,
            part: None,
            key: None,
            classes: &[],
            bindings: &[],
            children: &[],
        }
    }

    /// Creates a surface-only node.
    #[must_use]
    #[inline]
    pub const fn surface() -> Self {
        Self::widget(TemplateWidgetFactory::surface())
    }

    /// Assigns this node to a semantic template slot.
    #[must_use]
    #[inline]
    pub const fn with_slot(mut self, slot: TemplateSlot) -> Self {
        self.slot = Some(slot);
        self
    }

    /// Marks the node as an owner-local named part.
    #[must_use]
    #[inline]
    pub const fn with_part(mut self, part: PartTag) -> Self {
        self.part = Some(part);
        self
    }

    /// Assigns a stable key for a repeated part.
    #[must_use]
    #[inline]
    pub const fn with_key(mut self, key: TemplateItemKey) -> Self {
        self.key = Some(key);
        self
    }

    /// Adds classes to the generated element.
    #[must_use]
    #[inline]
    pub const fn with_classes(mut self, classes: &'static [ClassId]) -> Self {
        self.classes = classes;
        self
    }

    /// Adds owner-to-node property bindings to the generated element.
    #[must_use]
    #[inline]
    pub const fn with_bindings(mut self, bindings: &'static [TemplateBinding]) -> Self {
        self.bindings = bindings;
        self
    }

    /// Adds child nodes under this generated element.
    #[must_use]
    #[inline]
    pub const fn with_children(mut self, children: &'static [Self]) -> Self {
        self.children = children;
        self
    }

    /// Returns this node's widget factory.
    #[must_use]
    #[inline]
    pub const fn widget_factory(&self) -> TemplateWidgetFactory {
        self.widget
    }

    /// Returns this node's semantic slot, if any.
    #[must_use]
    #[inline]
    pub const fn slot(&self) -> Option<TemplateSlot> {
        self.slot
    }

    /// Returns this node's part tag, if any.
    #[must_use]
    #[inline]
    pub const fn part(&self) -> Option<PartTag> {
        self.part
    }

    /// Returns this node's repeated-item key, if any.
    #[must_use]
    #[inline]
    pub const fn key(&self) -> Option<TemplateItemKey> {
        self.key
    }

    /// Returns this node's classes.
    #[must_use]
    #[inline]
    pub const fn classes(&self) -> &'static [ClassId] {
        self.classes
    }

    /// Returns this node's bindings.
    #[must_use]
    #[inline]
    pub const fn bindings(&self) -> &'static [TemplateBinding] {
        self.bindings
    }

    /// Returns this node's children.
    #[must_use]
    #[inline]
    pub const fn children(&self) -> &'static [Self] {
        self.children
    }
}

/// Built-in properties addressable from data-driven template bindings.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum TemplateBuiltInProperty {
    /// `Background`.
    Background,
    /// `Bounds`.
    Bounds,
    /// `CornerRadius`.
    CornerRadius,
    /// `Layout`.
    Layout,
    /// `Content`.
    Content,
    /// `Foreground`.
    Foreground,
    /// `FontSize`.
    FontSize,
    /// `BorderBrush`.
    BorderBrush,
    /// `BorderWidth`.
    BorderWidth,
    /// `IsChecked`.
    IsChecked,
    /// `IsEnabled`.
    IsEnabled,
    /// `Value`.
    Value,
    /// `Minimum`.
    Minimum,
    /// `Maximum`.
    Maximum,
}

/// One owner-to-generated-node binding in a [`TemplateSpec`].
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct TemplateBinding {
    source: TemplateBuiltInProperty,
    target: TemplateBuiltInProperty,
}

impl TemplateBinding {
    /// Creates a binding from an owner property to the generated node.
    #[must_use]
    #[inline]
    pub const fn owner_to_part(
        source: TemplateBuiltInProperty,
        target: TemplateBuiltInProperty,
    ) -> Self {
        Self { source, target }
    }

    /// Returns the owner-side property.
    #[must_use]
    #[inline]
    pub const fn source(&self) -> TemplateBuiltInProperty {
        self.source
    }

    /// Returns the generated-node-side property.
    #[must_use]
    #[inline]
    pub const fn target(&self) -> TemplateBuiltInProperty {
        self.target
    }
}

fn instantiate_spec_node(
    cx: &mut TemplateContext<'_>,
    parent: ElementId,
    node: &TemplateNode,
) -> ElementId {
    let mut child = TemplateChild::widget(node.widget.create());
    if let Some(slot) = node.slot {
        child = child.with_slot(slot);
    }
    if let Some(part) = node.part {
        child = child.with_part(part);
    }
    if let Some(key) = node.key {
        child = child.with_key(key);
    }
    let id = cx.insert_under(parent, child);

    for class in node.classes {
        cx.add_class(id, *class);
    }
    for binding in node.bindings {
        apply_template_binding(cx, id, *binding);
    }
    for child in node.children {
        instantiate_spec_node(cx, id, child);
    }
    id
}

fn apply_template_binding(
    cx: &mut TemplateContext<'_>,
    target: ElementId,
    binding: TemplateBinding,
) {
    use TemplateBuiltInProperty::{
        Background, BorderBrush, BorderWidth, Bounds, Content, CornerRadius, FontSize, Foreground,
        IsChecked, IsEnabled, Layout, Maximum, Minimum, Value,
    };

    let props = *cx.properties();
    let result = match (binding.source, binding.target) {
        (Background, Background) => cx
            .bind_owner_to_part(props.background, target, props.background)
            .map(|_| ()),
        (Bounds, Bounds) => cx
            .bind_owner_to_part(props.bounds, target, props.bounds)
            .map(|_| ()),
        (CornerRadius, CornerRadius) => cx
            .bind_owner_to_part(props.corner_radius, target, props.corner_radius)
            .map(|_| ()),
        (Layout, Layout) => cx
            .bind_owner_to_part(props.layout, target, props.layout)
            .map(|_| ()),
        (Content, Content) => cx
            .bind_owner_to_part(props.content, target, props.content)
            .map(|_| ()),
        (Foreground, Foreground) => cx
            .bind_owner_to_part(props.foreground, target, props.foreground)
            .map(|_| ()),
        (FontSize, FontSize) => cx
            .bind_owner_to_part(props.font_size, target, props.font_size)
            .map(|_| ()),
        (BorderBrush, BorderBrush) => cx
            .bind_owner_to_part(props.border_brush, target, props.border_brush)
            .map(|_| ()),
        (BorderWidth, BorderWidth) => cx
            .bind_owner_to_part(props.border_width, target, props.border_width)
            .map(|_| ()),
        (IsChecked, IsChecked) => cx
            .bind_owner_to_part(props.is_checked, target, props.is_checked)
            .map(|_| ()),
        (IsEnabled, IsEnabled) => cx
            .bind_owner_to_part(props.is_enabled, target, props.is_enabled)
            .map(|_| ()),
        (Value, Value) => cx
            .bind_owner_to_part(props.value, target, props.value)
            .map(|_| ()),
        (Minimum, Minimum) => cx
            .bind_owner_to_part(props.minimum, target, props.minimum)
            .map(|_| ()),
        (Maximum, Maximum) => cx
            .bind_owner_to_part(props.maximum, target, props.maximum)
            .map(|_| ()),
        _ => panic!(
            "TemplateSpec binding requires matching built-in property types: {:?} -> {:?}",
            binding.source, binding.target
        ),
    };
    result.expect("TemplateSpec binding should be valid");
}
