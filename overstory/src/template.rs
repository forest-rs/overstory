//! Templates: factories that build a templated control's visual subtree.
//!
//! A [`Template`] is a reusable factory stored in the
//! [`crate::BuiltInProperties::control_template`] property by a local value,
//! app style rule, or framework default style. The [`crate::Ui`]
//! expands the resolved template when a widget element is inserted or when
//! template resolution changes. The template receives a [`TemplateContext`],
//! which tags each generated node with a `templated_parent: Option<ElementId>`
//! back-reference (see
//! [`crate::Element::templated_parent`]) and records the resulting parts in a
//! retained [`TemplateInstance`].
//!
//! Default templates can also label generated nodes with owner-local part
//! identities (see [`crate::Element::part_tag`]) so style rules can target
//! `Button > label` or `Slider > thumb` without treating parts as globally
//! unique widget types.
//!
//! ## Identity model
//!
//! Templates use several kinds of identity, and they are intentionally not
//! interchangeable:
//!
//! - [`understory_style::TypeTag`] is global selector identity for a real
//!   widget or control kind. A `Button`, `Slider`, or custom app control can
//!   have one because rules may reasonably target every instance of that kind.
//! - [`understory_style::PartTag`] is owner-local selector identity for an
//!   element generated by a template. A slider's `track` and `thumb` parts
//!   belong to that slider instance; they do not become app-wide widget types
//!   just because they can be styled.
//! - [`TemplateSlot`] is the semantic contract between a control and a template.
//!   It says which role a generated element fills for the owner. A slot may
//!   carry an owner-local part tag when that role should also be
//!   style-addressable.
//! - Classes and pseudoclasses are style-facing labels and state. They classify
//!   an element or expose interaction state, but they do not replace the
//!   control/template contract.
//!
//! For example, a slider element carries the global slider `TypeTag`. Its
//! default track and thumb are generated children with `templated_parent =
//! Some(slider)` and owner-local `PartTag`s, usually backed by
//! `SurfacePartWidget` with no global `TypeTag`. If a thumb later becomes a
//! reusable control with independent behavior, accessibility, or public
//! authoring API, it can graduate to its own widget type; pure visuals should
//! remain owner-local parts.
//!
//! A template-generated element does not need every kind of identity. Slots and
//! parts are independent axes:
//!
//! | Devtools label | Has `TemplateSlot` | Has `PartTag` | Meaning |
//! | --- | --- | --- | --- |
//! | `template child` | no | no | Generated structure only. Use this for private wrappers, layout helpers, or visuals that neither control behavior nor style rules need to address directly. |
//! | `template part` | no | yes | Style-addressable owner-local visual. Use this when a theme should target a generated element, but the control does not need to find it as part of its semantic contract. |
//! | `template slot` | yes | no | Semantic contract only. Use this when control behavior needs to find a generated element, but themes should not target it as an owner-local part. |
//! | `template slot part` | yes | yes | Semantic contract and style hook. This is common for built-in control parts such as `Button.Label`, `Slider.Track`, and `Slider.Thumb`. |
//!
//! Prefer the narrowest identity that does the job. Do not add a slot just
//! because a part needs styling, and do not add a part tag just because control
//! behavior needs to find a slot. Add both only when both the control contract
//! and style contract need to address the same generated element.
//!
//! Roadmap:
//! - Keep templates as the boundary between control behavior and visual
//!   structure: controls own state and semantics, templates own parts, slots,
//!   and layout of the visual subtree. See ticket `ove-733r`.
//! - Keep built-in default templates in style/property resolution so template
//!   identity, precedence, and retemplating all flow through
//!   `ControlTemplate`.
//! - Support both compact data-driven templates and custom code templates
//!   without requiring every visual variation to become a new widget type.
//! - Grow content slots, repeated keyed parts, optional slots, and eventual
//!   pseudo-elements into one predictable contract.
//! - Add diagnostics for required slots, duplicate keys, missing presenters,
//!   and template churn so custom templates fail loudly.
//! - Keep data flow semantic: presenters read owner content or control state at
//!   measure/present time, while normal property bindings remain part of the
//!   application property-binding runtime.

