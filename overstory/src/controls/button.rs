//! `Button`: clickable / keyboard-activatable templated control.
//!
//! Application code:
//!
//! ```ignore
//! ui.append(
//!     parent,
//!     Button::new("Click me")
//!         .font_size(22.0)
//!         .on_activate(|_, _| {}),
//! );
//! ```
//!
//! Roadmap:
//! - Keep `Button` as an activatable content control: the widget owns input,
//!   command-like activation, focus, and enabled semantics; templates own the
//!   visual tree.
//! - Keep activation semantic. Pointer clicks, keyboard activation, and
//!   accessibility click actions all dispatch [`ButtonActivatedEvent`]; app code
//!   that needs raw route phases should use [`Ui::events`] instead of
//!   `Button` builder callbacks.
//! - Move from string-only labels toward arbitrary content while preserving the
//!   simple `Button::new("Label")` path for common cases.
//! - Add mature activation affordances: default / cancel buttons, access keys,
//!   press-and-hold or repeat variants where those belong, and routed command
//!   integration.
//! - Make state styling complete across hover, press, focus-visible, disabled,
//!   and template-part states without special-casing the default template.
//! - Surface accessibility and automation metadata through the host layer while
//!   keeping renderer-specific behavior out of the control.

use alloc::boxed::Box;
use alloc::string::String;

use peniko::Brush;
use understory_style::{PartTag, TypeTag};

use crate::activation::ActivationSource;
use crate::behavior::WidgetEventContext;
use crate::controls::support::{CallbackSlot, EventHandler};
use crate::element::{Element, ElementId};
use crate::event_runtime::{ClickEvent, KeyEvent};
use crate::template::{
    TemplateContract, TemplateNode, TemplateSlot, TemplateSpec, TemplateSpecRecipe,
};
use crate::ui::{ControlState, Ui};
use crate::widget::{
    AppendSpec, ContentSlotSpec, ControlTemplateSpec, ElementConfig, ElementSpec, Widget,
};

/// Selector identity for `Button`.
pub const TYPE_BUTTON: TypeTag = TypeTag(2);
/// Owner-local part identity for the label generated by the default template.
pub const PART_BUTTON_LABEL: PartTag = PartTag(1);
/// Semantic slot for Button content.
pub const SLOT_BUTTON_CONTENT: TemplateSlot =
    TemplateSlot::new("content").with_part_tag(PART_BUTTON_LABEL);

/// Builder + spec for a `Button`. Use [`Button::new`] to start a
/// chain, configure with the chaining methods, and pass to
/// [`Ui::append`].
pub struct Button {
    content: String,
    font_size: Option<f64>,
    foreground: Option<Brush>,
    element: ElementConfig,
    on_activate: Option<ButtonActivatedHandler>,
}

type ButtonActivatedHandler = EventHandler<ButtonActivatedEvent>;
type ButtonActivatedSlot = CallbackSlot<ButtonActivatedEvent>;

/// Event delivered when a button is semantically activated.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ButtonActivatedEvent {
    /// Button element that was activated.
    pub element: ElementId,
    /// Input path that requested activation.
    pub source: ActivationSource,
}

impl core::fmt::Debug for Button {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("Button")
            .field("content", &self.content)
            .finish_non_exhaustive()
    }
}

impl Button {
    /// Starts a new `Button` builder with the given label.
    #[must_use]
    pub fn new(content: impl Into<String>) -> Self {
        let mut element = ElementConfig::default();
        element.set_focusable(true);
        Self {
            content: content.into(),
            font_size: None,
            foreground: None,
            element,
            on_activate: None,
        }
    }

    /// Overrides the button's font size (logical pixels).
    ///
    /// When unset, the value comes from the active style cascade.
    #[must_use]
    pub fn font_size(mut self, font_size: f64) -> Self {
        self.font_size = Some(font_size);
        self
    }

    /// Overrides the button's foreground brush. Default leaves it
    /// to the cascade (typically the theme's `ON_ACCENT_FG` token).
    #[must_use]
    pub fn foreground(mut self, brush: impl Into<Brush>) -> Self {
        self.foreground = Some(brush.into());
        self
    }

    /// Sets whether the button participates in focus traversal.
    /// Default `true`.
    #[must_use]
    pub fn focusable(mut self, focusable: bool) -> Self {
        self.element.set_focusable(focusable);
        self
    }

    /// Sets whether the button starts enabled. Disabled buttons are
    /// removed from focus traversal, ignore their builder-installed
    /// activation handlers, and carry `:disabled` for styling.
    #[must_use]
    pub fn enabled(mut self, enabled: bool) -> Self {
        self.element.set_enabled(enabled);
        self
    }

    /// Convenience for [`Self::enabled`] with `false`.
    #[must_use]
    pub fn disabled(self) -> Self {
        self.enabled(false)
    }

    /// Sets the shared construction-time control state.
    #[must_use]
    pub fn control_state(mut self, state: ControlState) -> Self {
        self.element.set_control_state(state);
        self
    }

    /// Registers a semantic activation handler.
    ///
    /// Activation fires for pointer clicks, keyboard activation (Space / Enter
    /// while focused), and supported accessibility actions. Use
    /// [`Ui::events`](crate::Ui::events) when an app needs raw routed pointer
    /// or key data instead of button intent.
    #[must_use]
    pub fn on_activate<F>(mut self, handler: F) -> Self
    where
        F: FnMut(&mut Ui, ButtonActivatedEvent) + 'static,
    {
        self.on_activate = Some(Box::new(handler));
        self
    }
}

impl AppendSpec for Button {
    fn append_to(self, ui: &mut Ui, parent: ElementId) -> ElementId {
        let id = ui
            .append_widget_deferred_template(parent, Box::new(ButtonWidget::new(self.on_activate)));
        let content_prop = ui.properties().content;
        let font_size_prop = ui.properties().font_size;
        let fg_prop = ui.properties().foreground;
        ui.set_local(id, content_prop, self.content);
        if let Some(font_size) = self.font_size {
            ui.set_local(id, font_size_prop, font_size);
        }
        if let Some(brush) = self.foreground {
            ui.set_local(id, fg_prop, brush);
        }
        self.element.apply_to(ui, id);
        ui.expand_resolved_template(id);
        id
    }
}

impl ControlTemplateSpec for Button {}

impl ContentSlotSpec for Button {
    const CONTENT_SLOT: TemplateSlot = SLOT_BUTTON_CONTENT;
}

impl ElementSpec for Button {
    fn element_config_mut(&mut self) -> &mut ElementConfig {
        &mut self.element
    }
}

/// Per-element widget for `Button`.
pub(crate) struct ButtonWidget {
    activated: ButtonActivatedSlot,
}

impl ButtonWidget {
    fn new(handler: Option<ButtonActivatedHandler>) -> Self {
        Self {
            activated: ButtonActivatedSlot::new(handler),
        }
    }

    fn activate(&self, ui: &mut Ui, button: ElementId, source: ActivationSource) {
        self.activated.dispatch(
            ui,
            button,
            ButtonActivatedEvent {
                element: button,
                source,
            },
        );
    }
}

impl core::fmt::Debug for ButtonWidget {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("ButtonWidget").finish_non_exhaustive()
    }
}

impl Widget for ButtonWidget {
    fn type_tag(&self) -> Option<TypeTag> {
        Some(TYPE_BUTTON)
    }

    fn accessibility_role(
        &self,
        _element: &Element,
        _ctx: &crate::AccessibilityContext<'_>,
    ) -> Option<accesskit::Role> {
        Some(accesskit::Role::Button)
    }

    fn configure_accessibility(
        &self,
        element: &Element,
        ctx: &crate::AccessibilityContext<'_>,
        node: &mut accesskit::Node,
    ) {
        ctx.add_click_action_if_enabled(element, node);
    }

    fn template_contract(&self) -> TemplateContract {
        TemplateContract::new().with_required_slot(SLOT_BUTTON_CONTENT)
    }

    fn handle_key(&mut self, ctx: &mut WidgetEventContext<'_>, event: KeyEvent<'_>) {
        use ui_events::keyboard::{Key, KeyState, NamedKey};
        let button = ctx.id();
        if !event.is_target() {
            return;
        }
        if event.key.state != KeyState::Down {
            return;
        }
        if !ctx.is_enabled(button) {
            return;
        }
        let activate = match &event.key.key {
            Key::Named(NamedKey::Enter) => true,
            Key::Character(s) if s == " " => true,
            _ => false,
        };
        if activate {
            self.activate(ctx, button, ActivationSource::Keyboard);
            event.mark_handled();
        }
    }

    fn handle_click(&mut self, ctx: &mut WidgetEventContext<'_>, event: ClickEvent<'_>) {
        let button = ctx.id();
        if !event.is_semantic_target() {
            return;
        }
        if !ctx.is_enabled(button) {
            return;
        }
        self.activate(ctx, button, ActivationSource::Pointer);
        event.mark_handled();
    }

    fn handle_accessibility_action(
        &mut self,
        ctx: &mut WidgetEventContext<'_>,
        request: &accesskit::ActionRequest,
    ) -> bool {
        let button = ctx.id();
        if request.action != accesskit::Action::Click || !ctx.is_enabled(button) {
            return false;
        }
        self.activate(ctx, button, ActivationSource::Accessibility);
        true
    }
}

static BUTTON_TEMPLATE: TemplateSpecRecipe = TemplateSpecRecipe::new(button_template_spec);

pub(crate) fn default_button_template() -> crate::ControlTemplate {
    crate::ControlTemplate::from_static(&BUTTON_TEMPLATE)
}

fn button_template_spec() -> TemplateSpec {
    // Foreground inherits through the tree, so styled owner foreground remains
    // theme-live instead of being copied into a local template value.
    TemplateSpec::from_nodes([TemplateNode::content_presenter(SLOT_BUTTON_CONTENT)])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::event_runtime::{RoutedHandlerOptions, RoutedHandlerScope};
    use crate::layouts::Layout;
    use accesskit::{Action, ActionRequest, TreeId};
    use alloc::rc::Rc;
    use alloc::vec::Vec;
    use core::cell::{Cell, RefCell};
    use kurbo::Size;
    use ui_events::keyboard::{Code, Key, KeyboardEvent, NamedKey};

    #[test]
    fn keyboard_activation_reports_keyboard_source() {
        let observed = Rc::new(Cell::new(None));
        let observed_for_handler = Rc::clone(&observed);
        let mut ui = Ui::new();
        let button = ui.append(
            ui.root(),
            Button::new("Run").on_activate(move |_ui, event| {
                observed_for_handler.set(Some((event.element, event.source)));
            }),
        );
        ui.set_focus(Some(button));

        let key = KeyboardEvent::key_down(Key::Named(NamedKey::Enter), Code::Enter);
        let result = ui.dispatch_key(&key);

        assert!(result.handled);
        assert_eq!(observed.get(), Some((button, ActivationSource::Keyboard)));
    }

    #[test]
    fn activation_runs_after_widget_restoration_and_routed_behavior() {
        let button_id = Rc::new(Cell::new(None));
        let button_id_for_handler = Rc::clone(&button_id);
        let order = Rc::new(RefCell::new(Vec::new()));
        let order_for_activation = Rc::clone(&order);
        let mut ui = Ui::new();
        let root = ui.root();
        let button = ui.append(
            root,
            Button::new("Run").on_activate(move |ui, _event| {
                let button = button_id_for_handler
                    .get()
                    .expect("button id is installed before activation");
                assert!(
                    ui.get(button).and_then(Element::widget).is_some(),
                    "semantic callbacks must observe their widget installed"
                );
                ui.add_class(button, ".activated");
                ui.set_layout(button, Layout::new().logical_size(120.0, 32.0));
                ui.compute_layout(Size::new(300.0, 100.0));
                order_for_activation.borrow_mut().push("semantic");
            }),
        );
        button_id.set(Some(button));
        let order_for_bubble = Rc::clone(&order);
        ui.events(root).key_with_options(
            RoutedHandlerOptions::new()
                .scope(RoutedHandlerScope::Bubble)
                .handled_events_too(true),
            move |_ui, _event| order_for_bubble.borrow_mut().push("bubble"),
        );
        ui.set_focus(Some(button));

        let key = KeyboardEvent::key_down(Key::Named(NamedKey::Enter), Code::Enter);
        let result = ui.dispatch_key(&key);

        assert!(result.handled);
        assert_eq!(order.borrow().as_slice(), ["bubble", "semantic"]);
        let activated = ui.class_id(".activated");
        assert!(ui.get(button).unwrap().classes().contains(&activated));
        assert_eq!(ui.effective_bounds(button).width(), 120.0);
    }

    #[test]
    fn activation_is_cancelled_if_routed_behavior_removes_button() {
        let activations = Rc::new(Cell::new(0));
        let activations_for_handler = Rc::clone(&activations);
        let mut ui = Ui::new();
        let root = ui.root();
        let button = ui.append(
            root,
            Button::new("Run").on_activate(move |_ui, _event| {
                activations_for_handler.set(activations_for_handler.get() + 1);
            }),
        );
        ui.events(root).key_with_options(
            RoutedHandlerOptions::new()
                .scope(RoutedHandlerScope::Bubble)
                .handled_events_too(true),
            move |ui, _event| ui.remove(button),
        );
        ui.set_focus(Some(button));

        let key = KeyboardEvent::key_down(Key::Named(NamedKey::Enter), Code::Enter);
        let result = ui.dispatch_key(&key);

        assert!(result.handled);
        assert!(ui.get(button).is_none());
        assert_eq!(activations.get(), 0);
    }

    #[test]
    fn accessibility_activation_reports_accessibility_source() {
        let observed = Rc::new(Cell::new(None));
        let observed_for_handler = Rc::clone(&observed);
        let mut ui = Ui::new();
        let button = ui.append(
            ui.root(),
            Button::new("Run").on_activate(move |_ui, event| {
                observed_for_handler.set(Some((event.element, event.source)));
            }),
        );

        let handled = ui.handle_accesskit_action(&ActionRequest {
            action: Action::Click,
            target_node: crate::accessibility::accesskit_node_id(button),
            target_tree: TreeId::ROOT,
            data: None,
        });

        assert!(handled);
        assert_eq!(
            observed.get(),
            Some((button, ActivationSource::Accessibility))
        );
    }
}
