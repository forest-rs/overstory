//! `ToggleSwitch`: two-state control with a sliding thumb.
//!
//! ```ignore
//! ui.append(parent, ToggleSwitch::new().checked(true));
//! ```
//!
//! Roadmap:
//! - Keep `ToggleSwitch` as an immediate on/off setting control, not a generic
//!   checkbox skin.
//! - Share checked state infrastructure with `CheckBox` while allowing switch
//!   specific visuals, animation, drag affordances, and accessibility role.
//! - Add optional on/off labels or content only through slots / templates so the
//!   control does not become layout-specific.
//! - Route state changes, focus, disabled behavior, and host accessibility
//!   actions through the same control-state and event systems used elsewhere.

use alloc::boxed::Box;

use understory_property::DependencyObjectExt;
use understory_style::{PartTag, TypeTag};

use crate::behavior::{ArrangeContext, ArrangeResult, WidgetEventContext};
use crate::controls::support::{
    CheckedChangedEvent, CheckedChangedHandler, CheckedChangedSlot, dispatch_checked_changed,
};
use crate::element::{Element, ElementId};
use crate::event_runtime::{ClickEvent, KeyEvent};
use crate::pseudos::PSEUDO_CHECKED;
use crate::template::{
    TemplateContract, TemplateNode, TemplateSlot, TemplateSpec, TemplateSpecRecipe,
};
use crate::timeline_runtime::{ChangeCause, TimelineTarget, VisualOutput};
use crate::ui::{ControlState, Ui};
use crate::widget::{AppendSpec, ControlTemplateSpec, ElementConfig, ElementSpec, Widget};

/// Selector identity for `ToggleSwitch`.
pub const TYPE_TOGGLE: TypeTag = TypeTag(3);
/// Owner-local part identity for the thumb generated by the default template.
pub const PART_TOGGLE_THUMB: PartTag = PartTag(1);
/// Semantic slot for the toggle thumb.
pub const SLOT_TOGGLE_THUMB: TemplateSlot =
    TemplateSlot::new("toggle-thumb").with_part_tag(PART_TOGGLE_THUMB);

/// Builder + spec for a `ToggleSwitch`.
pub struct ToggleSwitch {
    initial_checked: bool,
    element: ElementConfig,
    on_checked_changed: Option<CheckedChangedHandler>,
}

impl core::fmt::Debug for ToggleSwitch {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("ToggleSwitch")
            .field("initial_checked", &self.initial_checked)
            .finish_non_exhaustive()
    }
}

impl ToggleSwitch {
    /// Starts a new `ToggleSwitch` builder, off by default.
    #[must_use]
    pub fn new() -> Self {
        let mut element = ElementConfig::default();
        element.set_control_state(ControlState::interactive());
        Self {
            initial_checked: false,
            element,
            on_checked_changed: None,
        }
    }

    /// Sets the initial checked state.
    #[must_use]
    pub fn checked(mut self, checked: bool) -> Self {
        self.initial_checked = checked;
        self
    }

    /// Registers a handler fired after user input changes the checked state.
    #[must_use]
    pub fn on_checked_changed<F>(mut self, handler: F) -> Self
    where
        F: FnMut(&mut Ui, CheckedChangedEvent) + 'static,
    {
        self.on_checked_changed = Some(Box::new(handler));
        self
    }

    /// Sets whether the toggle participates in focus traversal.
    /// Default `true`.
    #[must_use]
    pub fn focusable(mut self, focusable: bool) -> Self {
        self.element
            .update_control_state(|state| state.focusable(focusable));
        self
    }

    /// Sets whether the toggle starts enabled. Disabled toggles are removed
    /// from focus traversal, ignore user activation, and carry `:disabled` for
    /// styling.
    #[must_use]
    pub fn enabled(mut self, enabled: bool) -> Self {
        self.element
            .update_control_state(|state| state.enabled(enabled));
        self
    }

    /// Convenience for [`Self::enabled`] with `false`.
    #[must_use]
    pub fn disabled(self) -> Self {
        self.enabled(false)
    }

    /// Sets the shared construction-time control state.
    #[must_use]
    pub fn control_state(mut self, state: ControlState) -> Self {
        self.element.set_control_state(state);
        self
    }
}

impl Default for ToggleSwitch {
    fn default() -> Self {
        Self::new()
    }
}

impl AppendSpec for ToggleSwitch {
    fn append_to(self, ui: &mut Ui, parent: ElementId) -> ElementId {
        let id = ui.append_widget_deferred_template(
            parent,
            Box::new(ToggleWidget::new(self.on_checked_changed)),
        );
        self.element.apply_to(ui, id);
        ui.expand_default_template(id);
        if self.initial_checked {
            set_toggle_checked(ui, id, true);
        }
        id
    }
}

impl ControlTemplateSpec for ToggleSwitch {}

impl ElementSpec for ToggleSwitch {
    fn element_config_mut(&mut self) -> &mut ElementConfig {
        &mut self.element
    }
}

/// Per-element widget for `ToggleSwitch`.
pub(crate) struct ToggleWidget {
    checked_changed: CheckedChangedSlot,
}

impl ToggleWidget {
    fn new(checked_changed: Option<CheckedChangedHandler>) -> Self {
        Self {
            checked_changed: CheckedChangedSlot::new(checked_changed),
        }
    }

    fn toggle_checked(&self, ui: &mut Ui, toggle: ElementId) {
        let next = toggle_checked_state(ui, toggle);
        dispatch_checked_changed(
            ui,
            &self.checked_changed,
            CheckedChangedEvent {
                element: toggle,
                checked: next,
            },
        );
    }
}

impl core::fmt::Debug for ToggleWidget {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("ToggleWidget").finish_non_exhaustive()
    }
}

impl Widget for ToggleWidget {
    fn type_tag(&self) -> Option<TypeTag> {
        Some(TYPE_TOGGLE)
    }

    fn accessibility_role(
        &self,
        _element: &Element,
        _ctx: &crate::AccessibilityContext<'_>,
    ) -> Option<accesskit::Role> {
        Some(accesskit::Role::Switch)
    }

    fn configure_accessibility(
        &self,
        element: &Element,
        ctx: &crate::AccessibilityContext<'_>,
        node: &mut accesskit::Node,
    ) {
        ctx.add_click_action_if_enabled(element, node);
        ctx.apply_checked_state(element, node);
    }

    fn default_template(&self) -> Option<crate::ControlTemplate> {
        Some(crate::ControlTemplate::from_static(&TOGGLE_TEMPLATE))
    }

    fn template_contract(&self) -> TemplateContract {
        TemplateContract::new().with_required_slot(SLOT_TOGGLE_THUMB)
    }

    fn handle_click(&mut self, ctx: &mut WidgetEventContext<'_>, event: ClickEvent<'_>) {
        let toggle = ctx.id();
        if !event.is_semantic_target() {
            return;
        }
        if !ctx.is_enabled(toggle) {
            return;
        }
        self.toggle_checked(ctx, toggle);
        event.mark_handled();
    }

    fn handle_key(&mut self, ctx: &mut WidgetEventContext<'_>, event: KeyEvent<'_>) {
        use ui_events::keyboard::{Key, KeyState, NamedKey};
        let toggle = ctx.id();
        if !event.is_target() {
            return;
        }
        if event.key.state != KeyState::Down {
            return;
        }
        if !ctx.is_enabled(toggle) {
            return;
        }
        let activate = match &event.key.key {
            Key::Named(NamedKey::Enter) => true,
            Key::Character(s) if s == " " => true,
            _ => false,
        };
        if activate {
            self.toggle_checked(ctx, toggle);
            event.mark_handled();
        }
    }

    fn arrange(&mut self, ctx: &mut ArrangeContext<'_>) -> ArrangeResult {
        let toggle = ctx.id();
        let _ = sync_thumb_offset_target(ctx.ui_mut(), toggle);
        ArrangeResult::UNCHANGED
    }
}

static TOGGLE_TEMPLATE: TemplateSpecRecipe = TemplateSpecRecipe::new(toggle_template_spec);

fn toggle_template_spec() -> TemplateSpec {
    // Thumb part. Sized + styled by the cascade.
    TemplateSpec::from_nodes([TemplateNode::surface_slot(SLOT_TOGGLE_THUMB)])
}

/// Flips `IsChecked` on `toggle` and keeps the `:checked`
/// pseudoclass in sync. Available as `pub` so app code or other
/// behaviors can drive a toggle without going through user input.
pub fn toggle_checked(ui: &mut Ui, toggle: ElementId) {
    let _ = toggle_checked_state(ui, toggle);
}

fn toggle_checked_state(ui: &mut Ui, toggle: ElementId) -> bool {
    let is_checked = ui.properties().is_checked;
    let was_checked = ui
        .get(toggle)
        .and_then(|el| el.get_local_value(is_checked).copied())
        .unwrap_or(false);
    let next = !was_checked;
    set_toggle_checked(ui, toggle, next);
    next
}

fn set_toggle_checked(ui: &mut Ui, toggle: ElementId, checked: bool) {
    let is_checked = ui.properties().is_checked;
    ui.set_local(toggle, is_checked, checked);
    if checked {
        ui.add_pseudo(toggle, PSEUDO_CHECKED);
    } else {
        ui.remove_pseudo(toggle, PSEUDO_CHECKED);
    }
    if let Some(thumb) = ui.slot(toggle, SLOT_TOGGLE_THUMB) {
        ui.request_styled_presentation_transition(
            thumb,
            TimelineTarget::VisualOutput(VisualOutput::LayerOffset),
        );
    }
}

fn sync_thumb_offset_target(ui: &mut Ui, toggle: ElementId) -> bool {
    let Some(thumb) = ui.slot(toggle, SLOT_TOGGLE_THUMB) else {
        return false;
    };
    let toggle_bounds = ui.effective_bounds(toggle);
    let thumb_bounds = ui.effective_bounds(thumb);
    let target = kurbo::Vec2::new(
        thumb_bounds.x0 - toggle_bounds.x0,
        thumb_bounds.y0 - toggle_bounds.y0,
    );
    let property = TimelineTarget::VisualOutput(VisualOutput::LayerOffset);
    let cause = if ui.has_pending_presentation_transition(thumb, property) {
        ChangeCause::Interaction
    } else {
        ChangeCause::Other
    };
    ui.set_presentation_target(thumb, property, target, cause)
}

#[cfg(test)]
mod tests {
    use super::*;
    use alloc::rc::Rc;
    use core::cell::Cell;
    use kurbo::Point;

    #[test]
    fn toggle_checked_changed_reports_new_state() {
        let observed = Rc::new(Cell::new(None));
        let observed_for_handler = Rc::clone(&observed);
        let mut ui = Ui::new();
        let root = ui.root();
        let toggle = ui.append(
            root,
            ToggleSwitch::new().on_checked_changed(move |_ui, event| {
                observed_for_handler.set(Some((event.element, event.checked)));
            }),
        );

        ui.synthesize_click(toggle, Point::ZERO);

        assert_eq!(observed.get(), Some((toggle, true)));
    }
}
