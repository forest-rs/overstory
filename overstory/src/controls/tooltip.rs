//! `Tooltip`: transient explanatory overlay attached to another element.
//!
//! ```ignore
//! let button = ui.append(parent, Button::new("Deploy"));
//! ui.set_tooltip(button, Tooltip::new("Runs the deploy workflow"));
//! ```

use alloc::boxed::Box;
use alloc::string::String;

use kurbo::{Rect, Size};
use peniko::Brush;
use understory_box_tree::NodeId;
use understory_presentation::{PresentationStore, TextContent};
use understory_style::{PartTag, TypeTag};

use crate::behavior::{MeasureConstraints, MeasureContext, PresentContext};
use crate::composition::CompositionPolicy;
use crate::element::{Element, ElementId};
use crate::layouts::Layout;
use crate::template::{
    Template, TemplateBinding, TemplateBuiltInProperty, TemplateNode, TemplateSlot, TemplateSpec,
    TemplateWidgetFactory,
};
use crate::ui::Ui;
use crate::widget::{AppendSpec, Widget};

/// Selector identity for `Tooltip`.
pub const TYPE_TOOLTIP: TypeTag = TypeTag(15);
/// Owner-local part identity for the tooltip label generated by the default template.
pub const PART_TOOLTIP_LABEL: PartTag = PartTag(1);
/// Semantic slot for tooltip label content.
pub const SLOT_TOOLTIP_CONTENT: TemplateSlot =
    TemplateSlot::new("content").with_part_tag(PART_TOOLTIP_LABEL);

/// Builder + retained configuration for a tooltip.
#[derive(Clone, Debug, PartialEq)]
pub struct Tooltip {
    content: String,
    font_size: f64,
    offset_x: f32,
    offset_y: f32,
    padding_x: f32,
    padding_y: f32,
}

impl Tooltip {
    /// Starts a new tooltip with the given label.
    #[must_use]
    pub fn new(content: impl Into<String>) -> Self {
        Self {
            content: content.into(),
            font_size: 13.0,
            offset_x: 0.0,
            offset_y: 8.0,
            padding_x: 10.0,
            padding_y: 6.0,
        }
    }

    /// Overrides the tooltip text font size in logical pixels.
    #[must_use]
    pub fn font_size(mut self, font_size: f64) -> Self {
        self.font_size = font_size;
        self
    }

    /// Offsets the tooltip from the target element's lower-left corner.
    #[must_use]
    pub fn offset(mut self, x: f32, y: f32) -> Self {
        self.offset_x = x;
        self.offset_y = y;
        self
    }

    /// Sets the tooltip's horizontal and vertical padding.
    #[must_use]
    pub fn padding(mut self, horizontal: f32, vertical: f32) -> Self {
        self.padding_x = horizontal;
        self.padding_y = vertical;
        self
    }

    /// Attaches this tooltip to `target` and returns `target` unchanged.
    pub fn attach_to(self, ui: &mut Ui, target: ElementId) -> ElementId {
        ui.set_tooltip(target, self);
        target
    }

    fn layout_for(&self, target_bounds: Rect) -> Layout {
        #[expect(
            clippy::cast_possible_truncation,
            reason = "tooltip coordinates fit the layout engine"
        )]
        let left = target_bounds.x0 as f32 + self.offset_x;
        #[expect(
            clippy::cast_possible_truncation,
            reason = "tooltip coordinates fit the layout engine"
        )]
        let top = target_bounds.y1 as f32 + self.offset_y;
        Layout::row(0.0)
            .align_center()
            .absolute_at(left, top)
            .padding_xy(self.padding_x, self.padding_y)
    }
}

impl AppendSpec for Tooltip {
    fn append_to(self, ui: &mut Ui, parent: ElementId) -> ElementId {
        append_tooltip(ui, parent, &self, Rect::ZERO)
    }
}

/// Per-element widget for `Tooltip`.
#[derive(Debug, Default)]
pub struct TooltipWidget;

impl Widget for TooltipWidget {
    fn type_tag(&self) -> Option<TypeTag> {
        Some(TYPE_TOOLTIP)
    }

    fn default_template(&self) -> Option<&'static dyn Template> {
        Some(&TOOLTIP_TEMPLATE)
    }

    fn is_hit_test_visible(&self, _element: &Element) -> bool {
        false
    }

    fn composition_policy(&self) -> CompositionPolicy {
        CompositionPolicy::OverlayScene
    }
}

#[derive(Debug, Default)]
struct TooltipLabelWidget;

impl Widget for TooltipLabelWidget {
    fn type_tag(&self) -> Option<TypeTag> {
        None
    }

    fn is_hit_test_visible(&self, _element: &Element) -> bool {
        false
    }

    fn present(
        &self,
        element: &Element,
        ctx: &PresentContext<'_>,
        store: &mut PresentationStore<NodeId, ElementId>,
        node: NodeId,
    ) {
        let content: String = ctx.get_value(element, ctx.properties.content);
        let foreground: Brush = ctx.get_value(element, ctx.properties.foreground);
        #[expect(clippy::cast_possible_truncation, reason = "font size fits f32")]
        let font_size = ctx.get_value(element, ctx.properties.font_size) as f32;

        let Some(text) = store.plain_text_mut(node) else {
            return;
        };
        text.content = TextContent::plain(content);
        text.foreground = Some(foreground);
        text.style.font_size = font_size;
    }

    fn measure(
        &self,
        element: &Element,
        ctx: &MeasureContext<'_>,
        constraints: MeasureConstraints,
    ) -> Option<Size> {
        let _ = constraints;
        let content: String = ctx.get_value(element, ctx.properties.content);
        if content.is_empty() {
            return Some(Size::ZERO);
        }
        #[expect(clippy::cast_possible_truncation, reason = "font size fits f32")]
        let font_size = ctx.get_value(element, ctx.properties.font_size) as f32;
        let foreground: Brush = ctx.get_value(element, ctx.properties.foreground);
        let layout = ctx
            .text
            .borrow_mut()
            .shape(&content, font_size, foreground, None);
        Some(Size::new(
            f64::from(layout.width()),
            f64::from(layout.height()),
        ))
    }
}

pub(crate) fn append_overlay_tooltip(
    ui: &mut Ui,
    tooltip: &Tooltip,
    target_bounds: Rect,
) -> ElementId {
    append_tooltip(ui, ui.root(), tooltip, target_bounds)
}

fn append_tooltip(
    ui: &mut Ui,
    parent: ElementId,
    tooltip: &Tooltip,
    target_bounds: Rect,
) -> ElementId {
    let id = ui.append_widget(parent, Box::new(TooltipWidget));
    let properties = *ui.properties();
    ui.set_local(id, properties.content, tooltip.content.clone());
    ui.set_local(id, properties.font_size, tooltip.font_size);
    ui.set_local(id, properties.layout, tooltip.layout_for(target_bounds));
    id
}

type TooltipTemplate = TemplateSpec;

static TOOLTIP_TEMPLATE: TooltipTemplate = TemplateSpec::new(TOOLTIP_TEMPLATE_NODES);

const TOOLTIP_LABEL_BINDINGS: &[TemplateBinding] = &[
    TemplateBinding::owner_to_part(
        TemplateBuiltInProperty::Content,
        TemplateBuiltInProperty::Content,
    ),
    TemplateBinding::owner_to_part(
        TemplateBuiltInProperty::FontSize,
        TemplateBuiltInProperty::FontSize,
    ),
];

const TOOLTIP_TEMPLATE_NODES: &[TemplateNode] =
    &[
        TemplateNode::widget(TemplateWidgetFactory::new(tooltip_label_widget))
            .with_slot(SLOT_TOOLTIP_CONTENT)
            .with_bindings(TOOLTIP_LABEL_BINDINGS),
    ];

fn tooltip_label_widget() -> Box<dyn Widget> {
    Box::new(TooltipLabelWidget)
}
