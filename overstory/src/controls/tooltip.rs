//! `Tooltip`: transient explanatory overlay attached to another element.
//!
//! ```ignore
//! let button = ui.append(parent, Button::new("Deploy"));
//! ui.set_tooltip(button, Tooltip::new("Runs the deploy workflow"));
//! ```
//!
//! Roadmap:
//! - Keep `Tooltip` transient, non-focusable, and non-interactive; interactive
//!   overlays should use popup / flyout controls.
//! - Move show / hide delay, hover intent, focus-triggered display, and pointer
//!   tracking into one tooltip service so targets do not manage stacks by hand.
//! - Share placement, collision, transforms, and overlay layering with `Popup`
//!   instead of maintaining a separate positioning model.
//! - Let templates style callouts, shadows, arrows, and text while the control
//!   owns accessibility description semantics and lifetime.

use alloc::boxed::Box;
use alloc::string::String;

use kurbo::{Point, Vec2};
use understory_presentation::Edges;
use understory_style::{PartTag, TypeTag};

use crate::composition::CompositionPolicy;
use crate::controls::support::box_padding_xy;
use crate::element::{Element, ElementId};
use crate::layouts::Layout;
use crate::overlay::Placement;
use crate::template::{
    TemplateContract, TemplateNode, TemplateSlot, TemplateSpec, TemplateSpecRecipe,
};
use crate::ui::Ui;
use crate::widget::{AppendSpec, ContentSlotSpec, ElementConfig, ElementSpec, Widget};

/// Selector identity for `Tooltip`.
pub const TYPE_TOOLTIP: TypeTag = TypeTag(15);
/// Owner-local part identity for the tooltip label generated by the default template.
pub const PART_TOOLTIP_LABEL: PartTag = PartTag(1);
/// Semantic slot for tooltip label content.
pub const SLOT_TOOLTIP_CONTENT: TemplateSlot =
    TemplateSlot::new("content").with_part_tag(PART_TOOLTIP_LABEL);

/// Builder + retained configuration for a tooltip.
#[derive(Clone, Debug)]
pub struct Tooltip {
    content: String,
    font_size: Option<f64>,
    placement: Placement,
    offset: Vec2,
    padding: Edges<f64>,
    element: ElementConfig,
}

impl Tooltip {
    /// Starts a new tooltip with the given label.
    #[must_use]
    pub fn new(content: impl Into<String>) -> Self {
        Self {
            content: content.into(),
            font_size: None,
            placement: Placement::BOTTOM_START,
            offset: Vec2::new(0.0, 8.0),
            padding: box_padding_xy(10.0, 6.0),
            element: ElementConfig::default(),
        }
    }

    /// Overrides the tooltip text font size in logical pixels.
    ///
    /// When unset, the value comes from the active style cascade.
    #[must_use]
    pub fn font_size(mut self, font_size: f64) -> Self {
        self.font_size = Some(font_size);
        self
    }

    /// Sets the tooltip's preferred placement around its target.
    #[must_use]
    pub fn placement(mut self, placement: Placement) -> Self {
        self.placement = placement;
        self
    }

    /// Offsets the tooltip from the placed edge of the target element.
    #[must_use]
    pub fn offset(mut self, x: f64, y: f64) -> Self {
        self.offset = Vec2::new(x, y);
        self
    }

    /// Sets the tooltip's horizontal and vertical padding.
    #[must_use]
    pub fn padding(mut self, horizontal: f64, vertical: f64) -> Self {
        self.padding = box_padding_xy(horizontal, vertical);
        self
    }

    /// Attaches this tooltip to `target` and returns `target` unchanged.
    pub fn attach_to(self, ui: &mut Ui, target: ElementId) -> ElementId {
        ui.set_tooltip(target, self);
        target
    }

    pub(crate) fn placement_value(&self) -> Placement {
        self.placement
    }

    pub(crate) fn offset_value(&self) -> Vec2 {
        self.offset
    }

    pub(crate) fn padding_edges(&self) -> Edges<f64> {
        self.padding
    }

    pub(crate) fn layout_for(&self, origin: Point) -> Layout {
        Layout::row(0.0)
            .align_center()
            .absolute_at(origin.x, origin.y)
    }
}

impl AppendSpec for Tooltip {
    fn append_to(self, ui: &mut Ui, parent: ElementId) -> ElementId {
        append_tooltip(ui, parent, &self, Point::ZERO)
    }
}

impl ContentSlotSpec for Tooltip {
    const CONTENT_SLOT: TemplateSlot = SLOT_TOOLTIP_CONTENT;
}

impl ElementSpec for Tooltip {
    fn element_config_mut(&mut self) -> &mut ElementConfig {
        &mut self.element
    }
}

/// Append wrapper that attaches a tooltip to the inserted element.
pub struct TooltipSpec<S> {
    spec: S,
    tooltip: Tooltip,
}

impl<S> core::fmt::Debug for TooltipSpec<S>
where
    S: core::fmt::Debug,
{
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("TooltipSpec")
            .field("spec", &self.spec)
            .field("tooltip", &self.tooltip)
            .finish()
    }
}

impl<S> TooltipSpec<S> {
    /// Creates a wrapper that attaches `tooltip` after `spec` is appended.
    #[must_use]
    pub fn new(spec: S, tooltip: Tooltip) -> Self {
        Self { spec, tooltip }
    }
}

impl<S> AppendSpec for TooltipSpec<S>
where
    S: AppendSpec,
{
    fn append_to(self, ui: &mut Ui, parent: ElementId) -> ElementId {
        let id = self.spec.append_to(ui, parent);
        ui.set_tooltip(id, self.tooltip);
        id
    }
}

impl<S> ElementSpec for TooltipSpec<S>
where
    S: ElementSpec,
{
    fn element_config_mut(&mut self) -> &mut ElementConfig {
        self.spec.element_config_mut()
    }
}

impl<S> ContentSlotSpec for TooltipSpec<S>
where
    S: ContentSlotSpec,
{
    const CONTENT_SLOT: TemplateSlot = S::CONTENT_SLOT;
}

/// Extension trait for attaching a tooltip at the same call-site as a spec.
pub trait TooltipSpecExt: AppendSpec + Sized {
    /// Attaches a default tooltip with text content to the inserted element.
    #[must_use]
    fn tooltip(self, content: impl Into<String>) -> TooltipSpec<Self> {
        self.with_tooltip(Tooltip::new(content))
    }

    /// Attaches a fully configured tooltip to the inserted element.
    #[must_use]
    fn with_tooltip(self, tooltip: Tooltip) -> TooltipSpec<Self> {
        TooltipSpec::new(self, tooltip)
    }
}

impl<S> TooltipSpecExt for S where S: AppendSpec {}

/// Per-element widget for `Tooltip`.
#[derive(Debug, Default)]
pub(crate) struct TooltipWidget;

impl Widget for TooltipWidget {
    fn type_tag(&self) -> Option<TypeTag> {
        Some(TYPE_TOOLTIP)
    }

    fn accessibility_role(
        &self,
        _element: &Element,
        _ctx: &crate::AccessibilityContext<'_>,
    ) -> Option<accesskit::Role> {
        Some(accesskit::Role::Tooltip)
    }

    fn template_contract(&self) -> TemplateContract {
        TemplateContract::new().with_required_slot(SLOT_TOOLTIP_CONTENT)
    }

    fn is_hit_test_visible(&self, _element: &Element) -> bool {
        false
    }

    fn composition_policy(&self) -> CompositionPolicy {
        CompositionPolicy::OverlayScene
    }
}

pub(crate) fn append_overlay_tooltip(ui: &mut Ui, tooltip: &Tooltip, origin: Point) -> ElementId {
    append_tooltip(ui, ui.root(), tooltip, origin)
}

fn append_tooltip(ui: &mut Ui, parent: ElementId, tooltip: &Tooltip, origin: Point) -> ElementId {
    let id = ui.append_widget(parent, Box::new(TooltipWidget));
    let properties = *ui.properties();
    ui.set_local(id, properties.content, tooltip.content.clone());
    if let Some(font_size) = tooltip.font_size {
        ui.set_local(id, properties.font_size, font_size);
    }
    ui.set_layout(id, tooltip.layout_for(origin));
    ui.set_box_padding(id, tooltip.padding_edges());
    tooltip.element.clone().apply_to(ui, id);
    id
}

static TOOLTIP_TEMPLATE: TemplateSpecRecipe = TemplateSpecRecipe::new(tooltip_template_spec);

pub(crate) fn default_tooltip_template() -> crate::ControlTemplate {
    crate::ControlTemplate::from_static(&TOOLTIP_TEMPLATE)
}

fn tooltip_template_spec() -> TemplateSpec {
    TemplateSpec::from_nodes([TemplateNode::content_presenter(SLOT_TOOLTIP_CONTENT)])
}
